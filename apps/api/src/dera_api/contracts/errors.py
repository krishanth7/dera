"""DERA API — RFC 9457 Problem Details and Error Taxonomy.

Defines the authoritative error code registry, field-level error details,
and RFC 9457-compliant Problem Details schemas for all client error responses.
"""

from enum import StrEnum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field
from starlette.responses import JSONResponse

PROBLEM_JSON_MEDIA_TYPE = "application/problem+json"


class ErrorCode(StrEnum):
    """Authoritative machine-readable error classification codes."""

    VALIDATION_ERROR = "VALIDATION_ERROR"
    MALFORMED_REQUEST = "MALFORMED_REQUEST"
    UNSUPPORTED_MEDIA_TYPE = "UNSUPPORTED_MEDIA_TYPE"
    RESOURCE_NOT_FOUND = "RESOURCE_NOT_FOUND"
    METHOD_NOT_ALLOWED = "METHOD_NOT_ALLOWED"
    CONFLICT = "CONFLICT"
    RATE_LIMITED = "RATE_LIMITED"
    INTERNAL_ERROR = "INTERNAL_ERROR"
    SERVICE_UNAVAILABLE = "SERVICE_UNAVAILABLE"
    DEPENDENCY_UNAVAILABLE = "DEPENDENCY_UNAVAILABLE"


class FieldErrorDetail(BaseModel):
    """Field-specific validation failure detail."""

    model_config = ConfigDict(frozen=True)

    field: str = Field(..., description="Dot-delimited JSON or query path of the invalid field.")
    code: str = Field(..., description="Machine-readable error token describing the constraint.")
    message: str = Field(..., description="Human-readable safe explanation of the violation.")
    constraint: str | None = Field(default=None, description="Optional violated constraint value.")


class ProblemDetail(BaseModel):
    """RFC 9457-compliant Problem Details representation for HTTP APIs."""

    model_config = ConfigDict(frozen=True)

    type: str = Field(
        default="about:blank",
        description="URI reference that identifies the problem type.",
    )
    title: str = Field(
        ...,
        description="Short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        ge=400,
        le=599,
        description="HTTP status code generated by the origin server.",
    )
    detail: str = Field(
        ...,
        description="Human-readable explanation specific to this occurrence of the problem.",
    )
    instance: str | None = Field(
        default=None,
        description="URI reference that identifies the specific occurrence of the problem.",
    )
    code: ErrorCode = Field(
        ...,
        description="Machine-readable DERA error classification code.",
    )
    request_id: str | None = Field(
        default=None,
        description="Correlation identifier for request tracing and log alignment.",
    )
    errors: list[FieldErrorDetail] | None = Field(
        default=None,
        description="Optional list of field-level validation errors.",
    )
    error: dict[str, Any] | None = Field(
        default=None,
        description="Backward-compatible error summary envelope.",
    )

    def to_response(self) -> JSONResponse:
        """Serializes problem detail into an RFC 9457 compliant JSONResponse."""
        return JSONResponse(
            status_code=self.status,
            content=self.model_dump(exclude_none=True),
            media_type=PROBLEM_JSON_MEDIA_TYPE,
        )
